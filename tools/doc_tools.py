PLAN_DOC_PROMPT = """你是一位文档结构设计专家。请产出文档大纲：
{template}

用户需求：{req}

先输出 Markdown 大纲（含各部分要点与预计篇幅），待确认后我再逐节撰写。"""

POLISH_DOC_PROMPT = """你是一位文书润色专家。请润色以下内容：
1. 保持原意与结构，规范用语、消除口语化与重复
2. 统一术语与编号层级
3. 输出润色稿，附【修改说明】列出关键改动"""


def plan_doc(doc_type, topic, extra=""):
    template = DOC_PROMPTS.get(doc_type, DOC_PROMPTS["策划方案"])
    req = f"文档类型：{doc_type}；主题：{topic}；补充要求：{extra or '无'}"
    return PLAN_DOC_PROMPT.format(template=template, req=req)


def polish_doc(text):
    return POLISH_DOC_PROMPT + "\n\n原文：\n" + text


def summarize_material(material):
    return f"""你是一位资料整理专家。请把用户提供的材料整理为结构化摘要：
1. 核心结论（3条以内）
2. 关键数据与事实（列表）
3. 待核实/待补充事项
4. 可引用的要点

材料原文：
{material}"""
